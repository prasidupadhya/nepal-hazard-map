// Writes src/lakes.js: the 47 potentially dangerous glacial lakes (ICIMOD 2020, Table 5.6)
// whose outburst floods would reach Nepal. Volumes: ICIMOD (2011) bathymetric surveys where they exist;
// otherwise estimated from lake area (scripts/data/lake-areas.json) with Huggel et al. (2002).
// Run: node scripts/build-lakes.js
import fs from 'node:fs';
const src = JSON.parse(fs.readFileSync('scripts/data/pdgl-icimod-2020.json'));
// ICIMOD (2011) Glacial Lakes and GLOFs in Nepal, Table 7.1 (2009 bathymetry): storage volume, million m³
const SURVEY = { GL086476E27861N: 85.94, GL086925E27898N: 35.5, GL084485E28488N: 35.37 };
const areas = fs.existsSync('scripts/data/lake-areas.json') ? JSON.parse(fs.readFileSync('scripts/data/lake-areas.json')).areas : {};
const NE = { 'Lower Barun': 'तल्लो बरुण', Chamlang: 'चामलाङ', 'Hongu 2': 'होङ्गु २', 'Hongu 1': 'होङ्गु १', 'Imja Tsho': 'इम्जा छो', Lumding: 'लुम्डिङ', 'Tsho Rolpa': 'छो रोल्पा', Ganxico: 'गन्सिको', Lumichimi: 'लुमिचिमी', Thulagi: 'थुलागी' };
const BASIN = { Tamor: ['Tamor', 'तमोर'], Arun: ['Arun', 'अरुण'], Dudh: ['Dudh Koshi', 'दूधकोशी'], Tama: ['Tama Koshi', 'तामाकोशी'], Sun: ['Sun Koshi', 'सुनकोशी'], Trishuli: ['Trishuli', 'त्रिशूली'], Marsyangdi: ['Marsyangdi', 'मर्स्याङ्दी'], Mugu: ['Mugu Karnali', 'मुगु कर्णाली'], Kali: ['Mahakali', 'महाकाली'] };
const COUNTRY = { Nepal: ['Nepal', 'नेपाल'], China: ['Tibet, China', 'तिब्बत, चीन'], India: ['India', 'भारत'] };
const huggel = (km2) => (0.104 * (km2 * 1e6) ** 1.42) / 1e6; // million m³
const r1 = (x) => Math.round(x * 10) / 10;
const lakes = src.lakes.map((l) => {
  let vol = null, volSrc = null;
  if (SURVEY[l.id]) { const v = SURVEY[l.id]; vol = [r1(v * 0.5), r1(v)]; volSrc = 'survey'; } // half to all of the surveyed storage
  else if (areas[l.id]) { const v = huggel(areas[l.id]); vol = [r1(v * 0.7), r1(v * 1.5)]; volSrc = 'area'; }
  return { id: l.id, no: l.no, en: l.name || l.id, ne: l.name ? NE[l.name] : l.id, named: !!l.name, rank: l.rank,
    basin: BASIN[l.basin], country: COUNTRY[l.country], ll: l.ll, vol, volSrc, area: areas[l.id] ?? null, survey: SURVEY[l.id] ?? null };
});
fs.writeFileSync('src/lakes.js', `// Generated by scripts/build-lakes.js — do not edit by hand.
// ${src.source}
// Rank I = highest danger. vol = default volume range (million m³) for the scenario; volSrc says where it comes from.
export const LAKES = ${JSON.stringify(lakes)};
`);
console.log(lakes.length, 'lakes;', lakes.filter((l) => l.vol).length, 'with a volume');
